// Computes WCAG contrast for every foreground/background token pair in src/theme/tokens.css (light and dark).
// Writes docs/contrast.md and exits non-zero if any pair misses its target. Run: npm run contrast
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const css = readFileSync(resolve(root, 'src/theme/tokens.css'), 'utf8')

function block(selector) {
  const start = css.indexOf(selector)
  const open = css.indexOf('{', start)
  let depth = 0
  for (let i = open; i < css.length; i += 1) {
    if (css[i] === '{') depth += 1
    if (css[i] === '}' && --depth === 0) return css.slice(open + 1, i)
  }
  return ''
}
const parse = (text) => Object.fromEntries([...text.matchAll(/--([\w-]+):\s*(#[0-9A-Fa-f]{6})\b/g)].map((m) => [m[1], m[2]]))
const light = parse(block(':root {'))
const dark = { ...light, ...parse(block(":root[data-theme='dark']"))}

const lum = (hex) => {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
}
export const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p)
  return (x + 0.05) / (y + 0.05)
}

const TEXT = 4.5, UI = 3
const pairs = [
  ['text', 'surface', TEXT], ['text', 'desk', TEXT], ['text', 'sunken', TEXT], ['text', 'brand-tint', TEXT],
  ['muted', 'surface', TEXT], ['muted', 'desk', TEXT], ['muted', 'sunken', TEXT],
  ['on-brand', 'brand', TEXT], ['on-deep', 'brand-deep', TEXT], ['brand-text', 'surface', TEXT], ['brand-text', 'desk', TEXT],
  ['danger', 'surface', TEXT], ['danger', 'danger-tint', TEXT], ['success', 'surface', TEXT], ['success', 'success-tint', TEXT],
  ['info', 'surface', TEXT], ['info', 'info-tint', TEXT], ['warning', 'surface', TEXT], ['warning', 'warning-tint', TEXT],
  ['st-paid', 'st-paid-bg', TEXT], ['st-pending', 'st-pending-bg', TEXT], ['st-overdue', 'st-overdue-bg', TEXT],
  ['st-partial', 'st-partial-bg', TEXT], ['st-draft', 'st-draft-bg', TEXT], ['st-cancelled', 'st-cancelled-bg', TEXT],
  ['border-strong', 'surface', UI], ['focus', 'surface', UI], ['focus', 'desk', UI], ['focus', 'brand-tint', UI], ['brand', 'surface', UI],
  ['chart-1', 'surface', UI], ['chart-2', 'surface', UI], ['chart-3', 'surface', UI], ['chart-4', 'surface', UI], ['chart-5', 'surface', UI],
]

let failures = 0
const rows = []
for (const [theme, map] of [['Light', light], ['Dark', dark]]) {
  for (const [fg, bg, target] of pairs) {
    if (!map[fg] || !map[bg]) continue
    const r = ratio(map[fg], map[bg])
    const pass = r >= target
    if (!pass) failures += 1
    rows.push(`| ${theme} | \`--${fg}\` ${map[fg]} | \`--${bg}\` ${map[bg]} | ${r.toFixed(2)}:1 | ${target}:1 | ${pass ? 'Pass' : '**FAIL**'} |`)
  }
}
const out = `# Contrast report\n\nGenerated by \`npm run contrast\` from \`src/theme/tokens.css\`. Text pairs target 4.5:1 (WCAG 1.4.3); UI components and graphics target 3:1 (1.4.11).\n\n| Theme | Foreground | Background | Ratio | Target | Result |\n|---|---|---|---|---|---|\n${rows.join('\n')}\n\n${failures ? `**${failures} failing pair(s).**` : 'All pairs pass.'}\n\n## Known, deliberate exception\n\n\`--brand\` (#F26A1B) on the page background (\`--desk\`) is ${ratio(light.brand, light.desk).toFixed(2)}:1. The brand orange is used for decoration (the letterhead accent, the active-nav marker) and as a fill that carries ink text (5.9:1). It is never the only boundary of a control and never the focus ring: the focus ring uses \`--focus\`.\n`
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(resolve(root, 'docs'), { recursive: true })
  writeFileSync(resolve(root, 'docs/contrast.md'), out)
  console.log(`${rows.length} pairs checked, ${failures} failing. Report: docs/contrast.md`)
  if (failures) console.log(rows.filter((r) => r.includes('FAIL')).join('\n'))
  process.exit(failures ? 1 : 0)
}
